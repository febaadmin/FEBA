#!/usr/bin/env python3
"""
Contrôle des textes visibles : recherche le tiret cadratin et les tournures
de rédaction automatique dans ce qui peut s'afficher. Sont hors contrôle les
commentaires, les docstrings, les journaux, les tests et les migrations.

Usage : scripts/controle_textes.py [--rapport fichier.json]
Sortie 1 s'il reste une occurrence visible. Les fichiers .js et .jsx sont
contrôlés par frontend/src/i18n/textesVisibles.test.js, seul à les analyser.
"""
import argparse
import ast
import json
import re
import sys
from pathlib import Path

RACINE = Path(__file__).resolve().parents[1]
TIRET = "—"
SIGNATURES = re.compile(
    r"as an ai\b|en tant qu'(ia|intelligence artificielle)|generated by (ai|chatgpt|claude)|"
    r"lorem ipsum|n'hésitez pas à|il est important de noter|bien sûr\s*!|je suis ravi|"
    r"john doe|jane doe|dummy text|texte de démonstration",
    re.I,
)
EXCLUS = re.compile(r"(^|/)(migrations|management|tests?|node_modules|dist|docs|e2e|__pycache__)/|\.test\.|/_archive/")
SUFFIXES_BRUTS = {".html", ".txt", ".json", ".svg", ".webmanifest", ".xml"}
RACINES = ("backend/apps", "backend/templates", "frontend/index.html", "frontend/public", "plugnmeet/client-branding")


def textes_python(chemin):
    arbre = ast.parse(chemin.read_text(encoding="utf-8"))
    ignores = set()
    for noeud in ast.walk(arbre):
        if isinstance(noeud, ast.Expr) and isinstance(noeud.value, ast.Constant):
            ignores.add(id(noeud.value))
        if isinstance(noeud, ast.Call) and isinstance(noeud.func, ast.Attribute) and (
                getattr(noeud.func.value, "id", "") == "logger" or noeud.func.attr in ("compile", "sub", "search", "match")):
            ignores.update(id(n) for n in ast.walk(noeud))
    for noeud in ast.walk(arbre):
        if isinstance(noeud, ast.Constant) and isinstance(noeud.value, str) and id(noeud) not in ignores:
            yield noeud.lineno, noeud.value


def textes_bruts(chemin):
    for numero, ligne in enumerate(chemin.read_text(encoding="utf-8", errors="ignore").splitlines(), 1):
        yield numero, ligne


def fichiers():
    for racine in RACINES:
        depart = RACINE / racine
        for chemin in ([depart] if depart.is_file() else depart.rglob("*") if depart.exists() else []):
            nom = chemin.relative_to(RACINE).as_posix()
            if chemin.is_file() and not EXCLUS.search(nom) and (chemin.suffix == ".py" or chemin.suffix in SUFFIXES_BRUTS):
                yield nom, chemin


def analyser():
    ecarts = []
    for nom, chemin in fichiers():
        lecture = textes_python if chemin.suffix == ".py" else textes_bruts
        for ligne, texte in lecture(chemin):
            if TIRET in texte:
                ecarts.append({"fichier": nom, "ligne": ligne, "type": "tiret", "texte": texte.strip()[:90]})
            if SIGNATURES.search(texte):
                ecarts.append({"fichier": nom, "ligne": ligne, "type": "signature", "texte": texte.strip()[:90]})
    return ecarts


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rapport")
    args = parser.parse_args()
    ecarts = analyser()
    if args.rapport:
        Path(args.rapport).write_text(json.dumps(ecarts, ensure_ascii=False, indent=1), encoding="utf-8")
    for e in ecarts:
        print(f"{e['fichier']}:{e['ligne']} [{e['type']}] {e['texte']}")
    print(f"{len(ecarts)} occurrence(s) visible(s)")
    return 1 if ecarts else 0


if __name__ == "__main__":
    sys.exit(main())
